async function launchNative(session) {
  const server = net.createServer(); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const port = server.address().port; await new Promise(resolve => server.close(resolve));
  const child = spawn(path.resolve(process.env.NZIP_NATIVE_EXE || `dist/NZIP-${require('../package.json').version}-win-x64/NZIP.exe`), [], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, NZIP_USER_DATA: path.join(session, 'profile'), NZIP_TEST_MODE: '1', WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS: `--remote-debugging-port=${port} --remote-debugging-address=127.0.0.1` } });
  let stderr = ''; child.stderr.on('data', d => stderr += d);
  let browser;
  const deadline = Date.now() + 30000;
  while (Date.now() < deadline) { try { browser = await chromium.connectOverCDP(`http://127.0.0.1:${port}`, { timeout: 1000 }); break; } catch { if (child.exitCode !== null) throw new Error(`Native app exited: ${stderr}`); await new Promise(resolve => setTimeout(resolve, 150)); } }
  if (!browser) { child.kill(); throw new Error(`Native app did not expose its test connection: ${stderr}`); }
  const page = browser.contexts()[0].pages()[0];
  return { firstWindow: async () => page, openViaShell: async (flag, file) => { const secondary = spawn(path.resolve(process.env.NZIP_NATIVE_EXE || `dist/NZIP-${require('../package.json').version}-win-x64/NZIP.exe`), [flag, file], { windowsHide: true, stdio: 'ignore', env: { ...process.env, NZIP_USER_DATA: path.join(session, 'profile') } }); const [code] = await once(secondary, 'exit'); assert.equal(code, 0); }, close: async () => { await page.evaluate(() => window.nzip.window('close')).catch(() => {}); await browser.close().catch(() => {}); await Promise.race([once(child, 'exit'), new Promise(resolve => setTimeout(resolve, 5000))]); if (child.exitCode === null) child.kill(); } };
}
main().catch(e => { console.error(e); process.exitCode = 1; });
